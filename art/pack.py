#!/usr/bin/env python3
"""Pack art/poses/*.png into src/23-art.js as WebP data URLs. Feet = centre of the lowest 40 px of ink."""
import base64, glob, io, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# poses whose lowest ink is not where he stands: ride has the back boot sunk into the cloud
FOOT = {'ride': (320, 640)}
rows = []
for p in sorted(glob.glob(os.path.join(ROOT, 'art', 'poses', '*.png'))):
    im = Image.open(p).convert('RGBA')
    a = np.asarray(im)[..., 3] > 128
    ys, xs = np.where(a); bot = int(ys.max()); fx = xs[ys > bot - 40]
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=88, method=6)
    url = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    k = os.path.splitext(os.path.basename(p))[0]
    foot = FOOT.get(k, (int(fx.mean()), bot))
    rows.append(f"  {k}: {{ w: {im.width}, h: {im.height}, foot: [{foot[0]}, {foot[1]}], src: '{url}' }},")
    print(k, im.size, round(len(url) / 1e3), 'KB')
out = '// ---------- art: painted key poses (generated by art/pack.py from art/poses; do not edit) ----------\nconst ART = {\n' + '\n'.join(rows) + '\n};\n'
open(os.path.join(ROOT, 'src', '23-art.js'), 'w', encoding='utf-8').write(out)
